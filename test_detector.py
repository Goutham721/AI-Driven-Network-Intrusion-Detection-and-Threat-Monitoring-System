def test_missing_model_raises_clear_error(monkeypatch):
    import src.predict as predict_module
    monkeypatch.setattr(predict_module, "_stage1_model", None)
    monkeypatch.setattr(predict_module, "STAGE1_MODEL_PATH", "models/does_not_exist.pkl")
    with pytest.raises(FileNotFoundError):
        predict_module._load_artifacts()
