"""
test_detector.py
Tests the end-to-end prediction pipeline against records generated by
each attack-pattern generator, plus basic error-handling cases.

Run:
    python -m pytest tests/test_detector.py -v
(Requires train_model.py to have been run first.)
"""

import os
import sys

import pytest

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from config import STAGE1_MODEL_PATH
from src.data_generator import (
    generate_brute_force_record,
    generate_ddos_record,
    generate_dos_record,
    generate_normal_record,
    generate_port_scan_record,
)
from src.predict import predict_record

MODELS_READY = os.path.exists(STAGE1_MODEL_PATH)


@pytest.mark.skipif(not MODELS_READY, reason="Model not trained yet")
def test_normal_traffic_detection():
    record = generate_normal_record()
    record.pop("label")
    result = predict_record(record)
    assert result["status"] in ("NORMAL", "ATTACK")  # model may disagree with generator label
    assert 0.0 <= result["confidence"] <= 1.0


